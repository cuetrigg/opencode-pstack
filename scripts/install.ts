import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const home = process.env.HOME || homedir()
const configHome = process.env.XDG_CONFIG_HOME || join(home, ".config")
const packageRoot = fileURLToPath(new URL("..", import.meta.url))
const agentsRoot = join(packageRoot, "content", "agents")
const installRoot = join(configHome, "opencode", "agents")
const marker = "<!-- generated by opencode-pstack; remove this line to keep your own copy -->"

mkdirSync(installRoot, { recursive: true })

for (const entry of readdirSync(agentsRoot, { withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith(".md")) continue

  const source = join(agentsRoot, entry.name)
  const destination = join(installRoot, entry.name)
  const generated = `${readFileSync(source, "utf8").trimEnd()}\n\n${marker}\n`

  if (existsSync(destination)) {
    const current = readFileSync(destination, "utf8")
    if (!current.includes(marker)) {
      console.warn(`skip ${destination}: an agent with this name already exists and was not generated by opencode-pstack`)
      continue
    }
  }

  writeFileSync(destination, generated)
  console.log(`installed ${destination}`)
}
