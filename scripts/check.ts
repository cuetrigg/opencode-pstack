import assert from "node:assert/strict"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"

const home = mkdtempSync(join(tmpdir(), "opencode-pstack-check-"))
process.env.HOME = home

const configDir = join(home, ".config", "opencode")
mkdirSync(configDir, { recursive: true })
writeFileSync(
  join(configDir, "pstack-models.md"),
  "# pstack model configuration for OpenCode\n# budget: large (xhigh)\njudgment and prose: inherit-parent\n",
)

const { default: plugin } = await import("../src/index.ts")

const skills: any[] = []
const commands: any[] = []
let contextHook: ((event: any) => void) | undefined
let prompted: any

const ctx: any = {
  agent: { reload: async () => {} },
  skill: {
    transform: async (callback: (editor: any) => void) => {
      callback({ add: (skill: any) => skills.push(skill) })
    },
  },
  command: {
    transform: async (callback: (editor: any) => void) => {
      callback({ add: (command: any) => commands.push(command) })
    },
  },
  session: {
    hook: async (_name: string, callback: (event: any) => void) => {
      contextHook = callback
      return { dispose: async () => {} }
    },
    prompt: async (input: any) => {
      prompted = input
    },
  },
}

await (plugin as any).setup(ctx)

assert.equal(skills.length, 58, "registers every pstack skill")
assert.equal(commands.length, 58, "registers one command per pstack skill")
assert.equal(skills.find((skill) => skill.id === "setup-pstack")?.autoinvoke, true)
assert.equal(skills.find((skill) => skill.id === "poteto-mode")?.autoinvoke, false)
assert.match(skills.find((skill) => skill.id === "poteto-mode")?.content, /# pstack in OpenCode/)
assert.match(skills.find((skill) => skill.id === "poteto-mode")?.content, /# Poteto mode/)

for (const agent of ["poteto-agent", "comment-sicko"]) {
  const installed = readFileSync(join(configDir, "agents", `${agent}.md`), "utf8")
  assert.match(installed, /^---\n/)
  assert.match(installed, /mode: subagent/)
  assert.match(installed, /generated by opencode-pstack/)
}

const potetoMode = commands.find((command) => command.name === "poteto-mode")
assert.ok(potetoMode)

await potetoMode.execute({
  sessionID: "ses_test",
  prompt: { text: "fix the bug", files: [], skills: [] },
  delivery: "steer",
})

assert.equal(prompted.sessionID, "ses_test")
assert.equal(prompted.text, "fix the bug")
assert.deepEqual(prompted.skills, [{ id: "poteto-mode" }])

assert.ok(contextHook)
const system: any[] = []
contextHook({ sessionID: "ses_test", system })
assert.ok(system.some((part) => part.text.includes("opencode-pstack:session")))
assert.ok(system.some((part) => part.text.includes("pstack model configuration")))

rmSync(home, { recursive: true, force: true })
console.log("opencode-pstack check: ok")
