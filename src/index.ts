import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import type { Plugin as PluginApi, Skill } from "@opencode/plugin"

const home = process.env.HOME || homedir()
const configHome = process.env.XDG_CONFIG_HOME || join(home, ".config")
const opencodeConfig = join(configHome, "opencode")
const packageRoot = fileURLToPath(new URL("..", import.meta.url))
const contentRoot = join(packageRoot, "content")
const skillsRoot = join(contentRoot, "skills")
const agentsRoot = join(contentRoot, "agents")
const harnessPath = join(contentRoot, "docs", "harness", "opencode.md")
const modelsPath = join(opencodeConfig, "pstack-models.md")
const agentInstallRoot = join(opencodeConfig, "agents")
const generatedAgentMarker = "<!-- generated by opencode-pstack; remove this line to keep your own copy -->"

interface ParsedSkill {
  id: string
  name: string
  description: string
  autoinvoke: boolean
  path: string
  content: string
}

function stripFrontmatter(source: string): { data: Record<string, string | boolean>; body: string } {
  if (!source.startsWith("---\n") && !source.startsWith("---\r\n")) {
    return { data: {}, body: source }
  }

  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(source)
  if (!match) return { data: {}, body: source }

  const data: Record<string, string | boolean> = {}
  const lines = match[1].split(/\r?\n/)

  for (let index = 0; index < lines.length; index++) {
    const line = lines[index]
    if (!line || /^\s/.test(line)) continue

    const entry = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line)
    if (!entry) continue

    const key = entry[1]
    let value = entry[2].trim()

    if (value === ">" || value === ">-" || value === "|" || value === "|-") {
      const folded = value.startsWith(">")
      const parts: string[] = []

      while (index + 1 < lines.length && (lines[index + 1].trim() === "" || /^\s/.test(lines[index + 1]))) {
        index++
        parts.push(lines[index].trim())
      }

      value = folded ? parts.join(" ").trim() : parts.join("\n").trim()
    } else if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1)
    }

    if (key === "disable-model-invocation") {
      data.autoinvoke = value !== "true"
    } else {
      data[key] = value
    }
  }

  return { data, body: source.slice(match[0].length) }
}

function loadSkills(harness: string): ParsedSkill[] {
  return readdirSync(skillsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const id = entry.name
      const path = join(skillsRoot, id, "SKILL.md")
      if (!existsSync(path)) return undefined

      const source = readFileSync(path, "utf8")
      const { data, body } = stripFrontmatter(source)
      const name = typeof data.name === "string" && data.name.length > 0 ? data.name : id
      const description = typeof data.description === "string" ? data.description : ""
      const autoinvoke = typeof data.autoinvoke === "boolean" ? data.autoinvoke : true

      return {
        id,
        name,
        description,
        autoinvoke,
        path,
        content: `${harness}\n\n---\n\n${body.trim()}\n`,
      }
    })
    .filter((skill): skill is ParsedSkill => skill !== undefined)
    .sort((a, b) => a.id.localeCompare(b.id))
}

function installAgents(): void {
  mkdirSync(agentInstallRoot, { recursive: true })

  for (const entry of readdirSync(agentsRoot, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) continue

    const source = join(agentsRoot, entry.name)
    const destination = join(agentInstallRoot, entry.name)
    const generated = `${readFileSync(source, "utf8").trimEnd()}\n\n${generatedAgentMarker}\n`

    if (existsSync(destination)) {
      const current = readFileSync(destination, "utf8")
      if (!current.includes(generatedAgentMarker)) continue
    }

    mkdirSync(dirname(destination), { recursive: true })
    writeFileSync(destination, generated)
  }
}

function readModelsRule(): string | undefined {
  if (!existsSync(modelsPath)) return undefined
  const rule = readFileSync(modelsPath, "utf8").trim()
  return rule.length > 0 ? rule : undefined
}

const pstack: PluginApi.Plugin = {
  id: "pstack",
  async setup(ctx) {
    const harness = readFileSync(harnessPath, "utf8").trim()
    const skills = loadSkills(harness)

    try {
      installAgents()
      await ctx.agent.reload()
    } catch (error) {
      console.warn(`opencode-pstack: could not install pstack agents: ${String(error)}`)
    }

    await ctx.skill.transform((editor) => {
      for (const skill of skills) {
        editor.add({
          id: skill.id as Skill.ID,
          name: skill.name as Skill.Name,
          description: skill.description || undefined,
          autoinvoke: skill.autoinvoke,
          path: skill.path as Skill.Info["path"],
          content: skill.content,
        })
      }
    })

    await ctx.command.transform((editor) => {
      for (const skill of skills) {
        editor.add({
          name: skill.id,
          description: skill.description || undefined,
          async execute({ sessionID, prompt, delivery }) {
            const attachments = prompt.skills ?? []
            await ctx.session.prompt({
              sessionID,
              text: prompt.text,
              files: prompt.files,
              agents: prompt.agents,
              skills: [...attachments, { id: skill.id }],
              delivery,
            })
          },
        })
      }
    })

    const models = await ctx.session.hook("context", (event) => {
      if (!event.system.some((part) => part.type === "text" && part.text.includes("opencode-pstack:session"))) {
        event.system.push({
          type: "text",
          text: `<!-- opencode-pstack:session -->\nCurrent OpenCode session ID: ${event.sessionID}. Export it with \`opencode session export ${event.sessionID}\`.`,
        })
      }

      const rule = readModelsRule()
      if (!rule) return
      if (event.system.some((part) => part.type === "text" && part.text.includes("opencode-pstack:models"))) return
      event.system.push({
        type: "text",
        text: `<!-- opencode-pstack:models -->\n${rule}`,
      })
    })

    return async () => {
      await models.dispose()
    }
  },
}

export default pstack
